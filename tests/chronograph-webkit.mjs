import { webkit, devices } from '@playwright/test';
import { preview } from 'vite';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';

const server = process.env.CHRONOGRAPH_BASE_URL ? null : await preview({ preview: { host: '127.0.0.1', port: 0 } });
const base = process.env.CHRONOGRAPH_BASE_URL || `http://127.0.0.1:${server.httpServer.address().port}`;
const browser = await webkit.launch();
const out = 'artifacts/chronograph_test/qa/';
await mkdir(out, { recursive: true });
try {
  const page = await browser.newPage({ ...devices['iPhone 15 Pro'], viewport: { width: 390, height: 844 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${base}/chronograph/?watch=marine-01`);
  await page.waitForFunction(() => window.chronograph?.snapshot.ready, null, { timeout: 120000 });
  const snapshot = () => page.evaluate(() => window.chronograph.snapshot);
  await page.getByRole('button', { name: 'Pause movement', exact: true }).tap();
  await page.getByRole('button', { name: 'Dial', exact: true }).tap();
  await page.waitForTimeout(1000);
  assert.equal((await snapshot()).glass.opacity, 0);
  assert.equal(await page.locator('canvas').evaluate(el => getComputedStyle(el).touchAction), 'none');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'Night lume', exact: true }).tap();
  await page.screenshot({ path: `${out}webkit-night.png` });
  await page.getByRole('button', { name: 'Night lume', exact: true }).tap();
  await page.getByRole('button', { name: '3x optical loupe', exact: true }).tap();
  assert.equal((await snapshot()).cameraZoom, 3);
  const canvas = await page.locator('canvas').boundingBox();
  const before = await page.locator('canvas').screenshot();
  await page.mouse.move(canvas.x + canvas.width / 2, canvas.y + canvas.height / 2);
  await page.mouse.down(); await page.mouse.move(canvas.x + canvas.width / 2 + 50, canvas.y + canvas.height / 2 + 30, { steps: 6 }); await page.mouse.up();
  await page.waitForTimeout(500);
  assert.notDeepEqual(await page.locator('canvas').screenshot(), before, 'Loupe scans actual geometry');
  await page.getByRole('button', { name: 'Under', exact: true }).tap();
  await page.waitForTimeout(500);
  assert.equal((await snapshot()).optics.underside, true);
  await page.screenshot({ path: `${out}webkit-underside.png` });
  await page.getByRole('button', { name: 'Turn sound on', exact: true }).tap();
  assert.equal((await snapshot()).audio.enabled, true);
  assert.equal((await snapshot()).audio.active, false);
  await page.getByRole('button', { name: 'Play movement', exact: true }).tap();
  await page.waitForFunction(() => window.chronograph.snapshot.audio.scheduled >= 3);
  await page.getByRole('button', { name: /Collection 01/ }).tap();
  assert.equal((await snapshot()).audio.active, false);
  assert.equal(await page.locator('#catalog-grid button').count(), 9);
  await page.getByRole('button', { name: 'Close collection' }).tap();
  assert.equal((await snapshot()).audio.active, true);
  await page.getByRole('button', { name: 'Turn sound off', exact: true }).tap();
  await page.getByRole('button', { name: 'Reset camera', exact: true }).tap();
  await page.screenshot({ path: `${out}webkit-overview.png` });
  assert.deepEqual(errors, []);
  const result = { passed: true, base, engine: 'Playwright WebKit on Windows; iPhone 15 Pro viewport', hardwareFPS: 'Not a physical iPhone benchmark', snapshot: await snapshot(), errors };
  await writeFile(`${out}webkit-validation.json`, JSON.stringify(result, null, 2));
  console.log(JSON.stringify({ passed: true, base, engine: result.engine }));
} finally { await browser.close(); if (server) await new Promise(resolve => server.httpServer.close(resolve)); }
