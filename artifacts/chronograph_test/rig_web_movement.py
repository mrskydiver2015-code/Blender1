"""Build named mechanical pivots from the editable hero and baked web scene.

Run after export_web.py. No geometry is invented or removed: static geometry
is consolidated by material, while moving assemblies retain separate pivots.
"""
import bpy, os, json, math, collections
from mathutils import Matrix, Vector

OUT = os.path.dirname(os.path.abspath(__file__))
hero = bpy.data.scenes['PATRIKS | No. 01 Marine Observatory']
baked = bpy.data.scenes['WEB | PATRIKS portable PBR']
bpy.context.window.scene = hero
bpy.context.view_layer.update()
depsgraph = bpy.context.evaluated_depsgraph_get()
assembly = bpy.data.objects['MARINE No.01 | inclined instrument assembly']
materials = {o.active_material.name.removeprefix('WEB | '): o.active_material for o in baked.objects}
rig_scene = bpy.data.scenes.new('WEB | PATRIKS live movement')
pivots = {}
specs = {
    'HourHand': ((0, 0, .35), math.radians(58)),
    'MinuteHand': ((0, 0, .376), math.radians(-49)),
    'SecondHand': ((0, 0, .415), math.radians(-166)),
    'SmallSecondsHand': ((-.652, .045, .322), 0),
    'GreatWheel_36T': ((-.075, -.48, .185), 0),
    'Pinion_12T': ((.213, -.48, .185), 0),
    'IntermediateWheel_20T': ((.213, -.288, .185), 0),
    'TourbillonCage': ((-.065, -.51, .281), 0),
    'BalanceWheel': ((-.065, -.51, .234), 0),
    'Hairspring': ((-.065, -.51, .255), 0),
}
for name, (position, rest_angle) in specs.items():
    pivot = bpy.data.objects.new(name, None)
    rig_scene.collection.objects.link(pivot)
    pivot.matrix_world = assembly.matrix_world @ Matrix.Translation(Vector(position))
    pivot['motionRole'] = name
    pivot['restAngle'] = rest_angle
    # Blender Z becomes glTF Y in the mesh/object local basis.
    pivot['motionAxis'] = [0, 1, 0]
    pivots[name] = pivot
anchor = bpy.data.objects.new('DialCenter', None)
rig_scene.collection.objects.link(anchor)
anchor.matrix_world = assembly.matrix_world @ Matrix.Translation((0, 0, .35))
anchor['motionRole'] = 'DialCenter'

def moving_group(source):
    name = source.name
    if name.startswith('HANDS | hour'): return 'HourHand'
    if name.startswith('HANDS | minute'): return 'MinuteHand'
    if name == 'HANDS | chronograph sweep': return 'SecondHand'
    if name == 'REGISTER | blued hand SECONDS': return 'SmallSecondsHand'
    if name == 'CALIBRE | 36T great wheel': return 'GreatWheel_36T'
    if name == 'CALIBRE | 12T interlocking pinion': return 'Pinion_12T'
    if name == 'CALIBRE | 20T intermediate wheel': return 'IntermediateWheel_20T'
    if name.startswith('CALIBRE | wheel spoke'):
        center = Vector(source.data.splines[0].points[0].co[:3])
        return min(['GreatWheel_36T', 'Pinion_12T', 'IntermediateWheel_20T'],
                   key=lambda key: (center - Vector(specs[key][0])).length)
    if name.startswith(('TOURBILLON | cage rim', 'TOURBILLON | three-arm bridge', 'TOURBILLON | cage jewel')):
        return 'TourbillonCage'
    if name.startswith(('TOURBILLON | balance rim', 'TOURBILLON | poising screw')):
        return 'BalanceWheel'
    if name == 'TOURBILLON | blued five-turn hairspring': return 'Hairspring'
    return None

groups = collections.defaultdict(list)
for source in hero.objects:
    if source.type not in {'MESH', 'CURVE', 'FONT'} or source.hide_render:
        continue
    if any(c.name.startswith(('07', '08')) for c in source.users_collection):
        continue
    material_name = source.data.materials[0].name
    if material_name.startswith(('05 |', '11 |')):
        # Retain exact baked UVs, generated by export_web.py.
        original = next(o for o in baked.objects if o.active_material == materials[material_name])
        mesh = original.data.copy()
        world_matrix = original.matrix_world.copy()
    else:
        mesh = bpy.data.meshes.new_from_object(source.evaluated_get(depsgraph),
            preserve_all_data_layers=True, depsgraph=depsgraph)
        world_matrix = source.matrix_world.copy()
    obj = bpy.data.objects.new(source.name + ' | web', mesh)
    rig_scene.collection.objects.link(obj)
    obj.matrix_world = world_matrix
    obj.data.materials.clear()
    obj.data.materials.append(materials[material_name])
    for polygon in obj.data.polygons: polygon.material_index = 0
    obj.data.validate(clean_customdata=False)
    group = moving_group(source)
    groups[(group, material_name)].append(obj)

bpy.context.window.scene = rig_scene
for (group, material), objects in groups.items():
    bpy.ops.object.select_all(action='DESELECT')
    for obj in objects: obj.select_set(True)
    bpy.context.view_layer.objects.active = objects[0]
    if len(objects) > 1: bpy.ops.object.join()
    obj = bpy.context.object
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    obj.name = (group + ' | ' + material) if group else ('SapphireCrystal' if material.startswith('10 |') else 'Static | ' + material)
    if group:
        world_matrix = obj.matrix_world.copy()
        obj.parent = pivots[group]
        obj.matrix_world = world_matrix

bpy.context.view_layer.update()
bpy.ops.object.select_all(action='SELECT')
bpy.ops.export_scene.gltf(
    filepath=os.path.join(OUT, 'chronograph_web.glb'), export_format='GLB',
    use_selection=True, use_active_scene=True, export_apply=True,
    export_draco_mesh_compression_enable=True, export_draco_mesh_compression_level=6,
    export_draco_position_quantization=18, export_draco_normal_quantization=14,
    export_draco_texcoord_quantization=14, export_extras=True,
    export_animations=False, export_cameras=False, export_lights=False)
triangles = 0
for obj in rig_scene.objects:
    if obj.type == 'MESH':
        obj.data.calc_loop_triangles()
        triangles += len(obj.data.loop_triangles)
receipt = {'movablePivots': list(pivots), 'rotationAxis': [0, 1, 0],
    'triangles': triangles, 'meshes': sum(o.type == 'MESH' for o in rig_scene.objects),
    'source': hero.name, 'bakedMaterials': baked.name, 'draco': True}
with open(os.path.join(OUT, 'movement_rig.json'), 'w') as handle:
    json.dump(receipt, handle, indent=2)
bpy.context.window.scene = hero
bpy.ops.wm.save_as_mainfile(filepath=os.path.join(OUT, 'chronograph_scene.blend'))
print('MOVEMENT_RIG', json.dumps(receipt))
